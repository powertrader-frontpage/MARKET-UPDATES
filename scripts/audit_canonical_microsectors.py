"""Read-only comparison of canonical master baskets with legacy app.py baskets."""
import ast
import csv
from pathlib import Path

import pandas as pd

# Allow direct execution as: python scripts/audit_canonical_microsectors.py
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from classification_master import load_classification_master
from canonical_microsectors import (
    build_canonical_classification, canonical_microsector_baskets,
    load_microsector_alias_map, validate_alias_symbol_coverage,
)

ROOT = Path(__file__).resolve().parents[1]
MASTER_PATH = ROOT / "data" / "stock_classification_master.csv"
ALIAS_PATH = ROOT / "data" / "microsector_canonical_alias_map.csv"
APP_PATH = ROOT / "app.py"
REPORT_PATH = ROOT / "reports" / "canonical_microsector_migration_audit.md"
DETAIL_PATH = ROOT / "reports" / "microsector_legacy_vs_canonical_membership.csv"


def legacy_baskets_from_app(path: Path) -> dict:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "MICRO_SECTORS"
            for target in node.targets
        ):
            value = ast.literal_eval(node.value)
            return {
                name: (group, sorted({str(symbol).upper() for symbol in symbols}))
                for name, (group, symbols) in value.items()
            }
    raise RuntimeError("MICRO_SECTORS literal assignment not found in app.py")


def main():
    master = load_classification_master(MASTER_PATH)
    aliases = load_microsector_alias_map(ALIAS_PATH)
    canonical = build_canonical_classification(master, aliases)
    alias_errors = validate_alias_symbol_coverage(master, aliases)
    canonical_baskets = canonical_microsector_baskets(canonical)
    legacy = legacy_baskets_from_app(APP_PATH)

    canonical_by_symbol = dict(zip(canonical["Symbol"], canonical["Canonical_Microsector"]))
    legacy_memberships = {}
    for name, (_, symbols) in legacy.items():
        for ticker in symbols:
            symbol = ticker.removesuffix(".NS").upper()
            legacy_memberships.setdefault(symbol, []).append(name)

    rows = []
    for symbol in sorted(set(canonical_by_symbol) | set(legacy_memberships)):
        primary = canonical_by_symbol.get(symbol, "")
        old = sorted(legacy_memberships.get(symbol, []))
        rows.append({
            "Symbol": symbol,
            "Canonical_Primary_Microsector": primary,
            "Legacy_Microsector_Count": len(old),
            "Legacy_Microsector_Labels": ";".join(old),
            "In_Canonical_Master": bool(primary),
            "In_Legacy_Dashboard": bool(old),
            "Membership_Status": (
                "MATCH_ONE_LABEL" if primary and old == [primary] else
                "LEGACY_MULTI_MEMBERSHIP" if len(old) > 1 else
                "LEGACY_LABEL_DIFFERS" if primary and old else
                "MASTER_ONLY" if primary else "LEGACY_ONLY"
            ),
        })
    detail = pd.DataFrame(rows)
    detail.to_csv(DETAIL_PATH, index=False, encoding="utf-8-sig")

    legacy_unique = {s for _, (_, symbols) in legacy.items() for s in symbols}
    canonical_unique = set(canonical_by_symbol)
    status_counts = detail["Membership_Status"].value_counts().to_dict()
    lines = [
        "# Canonical microsector migration audit",
        "",
        "Generated by `python scripts/audit_canonical_microsectors.py`.",
        "This is a read-only comparison. It does not modify app.py or live rotation logic.",
        "",
        "## Master and alias validation",
        f"- Verified master stocks: **{len(canonical):,}**",
        f"- Canonical microsectors: **{canonical['Canonical_Microsector'].nunique():,}**",
        f"- Approved aliases: **{len(aliases):,}**",
        f"- Alias symbol-coverage errors: **{len(alias_errors)}**",
        f"- Legacy microsector labels in app.py: **{len(legacy):,}**",
        f"- Unique legacy symbols: **{len(legacy_unique):,}**",
        f"- Canonical master symbols: **{len(canonical_unique):,}**",
        "",
        "## Membership comparison",
    ]
    lines.extend(f"- {key}: **{value:,}**" for key, value in sorted(status_counts.items()))
    lines += [
        "",
        "A strict label match is deliberately conservative: legacy labels are not assumed equivalent to canonical labels.",
        "Legacy baskets can contain overlapping memberships, while the master assigns exactly one verified primary microsector per stock.",
        "",
        "## Alias coverage errors",
    ]
    lines.extend([f"- {error}" for error in alias_errors] or ["- None"])
    lines += [
        "",
        "## Migration gate",
        "Do not replace the legacy baskets until every legacy-only symbol, master-only symbol, multi-membership, and label difference has been reviewed.",
        "Do not change return windows, equal-weight basket calculations, score weights, breadth formulas, zone thresholds, or Fyers/Yahoo data-source priority as part of taxonomy migration.",
        "",
        f"Detailed stock-level comparison: `{DETAIL_PATH.relative_to(ROOT)}`.",
        "",
    ]
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
