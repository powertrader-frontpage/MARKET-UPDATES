"""Build canonical microsector baskets in shadow mode.

This module is intentionally not imported by app.py. It validates exclusive
primary membership and writes review artifacts only; it does not fetch prices,
calculate returns, or alter live rotation logic.
"""
from pathlib import Path
import sys

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from classification_master import load_classification_master
from canonical_microsectors import (
    build_canonical_classification,
    canonical_microsector_baskets,
    load_microsector_alias_map,
    validate_alias_symbol_coverage,
)

MASTER = ROOT / "data" / "stock_classification_master.csv"
ALIASES = ROOT / "data" / "microsector_canonical_alias_map.csv"
BASKET_OUT = ROOT / "reports" / "canonical_microsector_shadow_baskets.csv"
SUMMARY_OUT = ROOT / "reports" / "canonical_microsector_shadow_summary.md"


def main():
    master = load_classification_master(MASTER)
    aliases = load_microsector_alias_map(ALIASES)
    errors = validate_alias_symbol_coverage(master, aliases)
    if errors:
        raise SystemExit("Alias coverage failed: " + " | ".join(errors))

    canonical = build_canonical_classification(master, aliases)
    baskets = canonical_microsector_baskets(canonical)
    membership = {}
    for label, tickers in baskets.items():
        for ticker in tickers:
            membership.setdefault(ticker, []).append(label)

    duplicated = {ticker: labels for ticker, labels in membership.items() if len(labels) != 1}
    expected = set(canonical["Symbol"].astype(str).str.upper())
    actual = {ticker.removesuffix(".NS") for ticker in membership}
    missing = sorted(expected - actual)
    unexpected = sorted(actual - expected)
    if duplicated or missing or unexpected:
        raise SystemExit(
            f"Shadow basket integrity failed: duplicate={duplicated}; "
            f"missing={missing}; unexpected={unexpected}"
        )

    rows = [
        {"Canonical_Microsector": label, "Stock_Count": len(tickers),
         "Tickers": ";".join(tickers), "Membership_Mode": "EXCLUSIVE_PRIMARY"}
        for label, tickers in sorted(baskets.items())
    ]
    pd.DataFrame(rows).to_csv(BASKET_OUT, index=False, encoding="utf-8-sig")

    multi_tag = canonical["MIT_Secondary_Tags"].fillna("").astype(str).str.strip().ne("")
    summary = [
        "# Canonical microsector shadow-mode build",
        "",
        "Generated by `python scripts/build_canonical_microsector_shadow.py`.",
        "",
        "- Mode: **SHADOW ONLY** — not imported by app.py.",
        f"- Verified stocks: **{len(canonical):,}**",
        f"- Canonical primary microsectors: **{len(baskets):,}**",
        f"- Total primary basket memberships: **{sum(map(len, baskets.values())):,}**",
        f"- Duplicate primary memberships: **{len(duplicated)}**",
        f"- Missing verified symbols: **{len(missing)}**",
        f"- Unexpected symbols: **{len(unexpected)}**",
        f"- Stocks with secondary tags: **{int(multi_tag.sum()):,}**",
        "",
        "## Integrity result",
        "- PASS: every verified stock appears in exactly one canonical primary basket.",
        "- PASS: no price, return, score, breadth, zone, ranking, or source-priority calculation is performed.",
        "- PASS: existing app.py MICRO_SECTORS and live rotation calculations remain untouched.",
        "",
        f"Basket detail: `{BASKET_OUT.relative_to(ROOT)}`.",
        "",
    ]
    SUMMARY_OUT.write_text("\n".join(summary), encoding="utf-8")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
